#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn numbers_round_trip() {
        for cp in Codepage::ALL {
            assert_eq!(Codepage::from_number(cp.number()), Some(cp));
        }
        assert_eq!(Codepage::from_number(1252), None);
        assert_eq!(Codepage::from_number(9999), None);
        assert_eq!(Codepage::default(), Codepage::Cp850);
    }

    #[test]
    fn known_characters_land_where_iconv_puts_them() {
        assert_eq!(Codepage::Cp437.encode('Ä'), Some(0x8e));
        assert_eq!(Codepage::Cp850.encode('Ä'), Some(0x8e));
        assert_eq!(Codepage::Cp852.encode('Ä'), Some(0x8e));
        assert_eq!(Codepage::Cp852.encode('Ł'), Some(0x9d));
        assert_eq!(Codepage::Cp866.encode('Ж'), Some(0x86));
        assert_eq!(Codepage::Cp866.encode('ё'), Some(0xf1));
        assert_eq!(Codepage::Cp437.encode('ß'), Some(0xe1));
        assert_eq!(Codepage::Cp850.encode('Ø'), Some(0x9d));
        assert_eq!(Codepage::Cp866.encode('Ä'), None);
        assert_eq!(Codepage::Cp437.encode('Ж'), None);
        assert_eq!(Codepage::Cp850.encode('€'), None);
        assert_eq!(Codepage::Cp850.encode('A'), Some(b'A'));
    }

    #[test]
    fn each_upper_half_is_a_bijection() {
        for cp in Codepage::ALL {
            for b in 0x80..=0xffu8 {
                let c = cp.decode(b);
                assert!(!c.is_ascii(), "CP{} {b:#x}", cp.number());
                assert_eq!(cp.encode(c), Some(b), "CP{} {b:#x}", cp.number());
            }
        }
    }
}
