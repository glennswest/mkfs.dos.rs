//! DOS code pages for the volume label — `mkfs.fat --codepage`.
//!
//! dosfstools 4.2 converts the label from the locale's encoding into the DOS
//! code page with iconv (`local_string_to_dos_string()` in `charconv.c`,
//! `CP<N>` without `//TRANSLIT`), 850 unless `--codepage` says otherwise.
//! This crate carries the four DOS code pages below. Their upper halves are
//! glibc's iconv tables, byte for byte (checked against glibc 2.42 both
//! ways: every byte 0x80–0xff decodes to the character listed, and no other
//! character encodes at all); the lower half is ASCII.
//!
//! What 4.2 then does with a converted label is the reason no byte of a
//! filesystem ever comes out of these tables: `validate_volume_label()`
//! compares each byte, a signed `char` on x86, with `< 0x20`, so every byte
//! from 0x80 up counts as a control character and the label is refused with
//! `Labels with characters below 0x20 are not allowed`. (Upstream fixed that
//! after 4.2, in c888797b1d.) The tables decide only which of 4.2's two
//! refusals a non-ASCII label gets — see [`crate::params::encode_label_in`].

/// A DOS code page a label can be given in, `--codepage N`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Codepage {
    /// CP437, the original IBM PC code page.
    Cp437,
    /// CP850, DOS Latin-1 — `DEFAULT_DOS_CODEPAGE`, what 4.2 uses without
    /// `--codepage`.
    #[default]
    Cp850,
    /// CP852, DOS Latin-2 (Central European).
    Cp852,
    /// CP866, DOS Cyrillic (Russian).
    Cp866,
}

impl Codepage {
    /// Every code page this crate carries, in number order.
    pub const ALL: [Codepage; 4] = [
        Codepage::Cp437,
        Codepage::Cp850,
        Codepage::Cp852,
        Codepage::Cp866,
    ];

    /// The code page's number: 437, 850, 852 or 866.
    pub fn number(self) -> u32 {
        match self {
            Codepage::Cp437 => 437,
            Codepage::Cp850 => 850,
            Codepage::Cp852 => 852,
            Codepage::Cp866 => 866,
        }
    }

    /// The code page numbered `n`, if this crate carries it.
    pub fn from_number(n: u32) -> Option<Codepage> {
        Codepage::ALL.into_iter().find(|c| c.number() == n)
    }

    fn high(self) -> &'static [u16; 128] {
        match self {
            Codepage::Cp437 => &CP437_HIGH,
            Codepage::Cp850 => &CP850_HIGH,
            Codepage::Cp852 => &CP852_HIGH,
            Codepage::Cp866 => &CP866_HIGH,
        }
    }

    /// The character byte `b` stands for in this code page.
    pub fn decode(self, b: u8) -> char {
        if b < 0x80 {
            return b as char;
        }
        // Every entry is a BMP scalar value, so this never falls back.
        char::from_u32(self.high()[(b - 0x80) as usize] as u32).unwrap_or('?')
    }

    /// The byte that stands for `c` in this code page, or `None` when the
    /// code page has no such character (iconv's `EILSEQ`).
    pub fn encode(self, c: char) -> Option<u8> {
        if c.is_ascii() {
            return Some(c as u8);
        }
        let u = u32::from(c);
        self.high()
            .iter()
            .position(|&h| u32::from(h) == u)
            .map(|i| 0x80 + i as u8)
    }
}

